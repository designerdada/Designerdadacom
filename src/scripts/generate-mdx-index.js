/**
 * Build script to automatically generate /content/writing/index.ts
 * from all MDX files in /content/writing/
 *
 * Run this before build: npm run generate:mdx
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const CONTENT_DIR = path.join(__dirname, '../content/writing');
const OUTPUT_FILE = path.join(CONTENT_DIR, 'index.ts');

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const frontmatter = {};
  match[1].split('\n').forEach(line => {
    const colonIndex = line.indexOf(':');
    if (colonIndex === -1) return;
    const key = line.slice(0, colonIndex).trim();
    const value = line.slice(colonIndex + 1).trim();
    if (key && value) frontmatter[key] = value;
  });
  return frontmatter;
}

function generateIndexFile() {
  console.log('🔍 Scanning for MDX files...');

  const files = fs.readdirSync(CONTENT_DIR)
    .filter(file =>
      file.endsWith('.mdx') &&
      !file.startsWith('_')
    );

  if (files.length === 0) {
    console.log('⚠️  No MDX files found in /content/writing/');
    return;
  }

  console.log(`📝 Found ${files.length} article(s):`);
  files.forEach(file => console.log(`   - ${file}`));

  const articleEntries = [];

  files.forEach(file => {
    const slug = path.basename(file, '.mdx');
    const filePath = path.join(CONTENT_DIR, file);
    const content = fs.readFileSync(filePath, 'utf-8');

    const frontmatter = parseFrontmatter(content);
    if (frontmatter.title && frontmatter.publishDate) {
      articleEntries.push({
        id: slug,
        title: frontmatter.title,
        date: frontmatter.publishDate,
      });
    }
  });

  // Sort articles by date (newest first)
  articleEntries.sort((a, b) => {
    const dateA = new Date(a.date.replace(/\./g, ' '));
    const dateB = new Date(b.date.replace(/\./g, ' '));
    return dateB.getTime() - dateA.getTime();
  });

  const articleListStr = articleEntries
    .map(a => `  { id: '${a.id}', title: '${a.title.replace(/'/g, "\\'")}', date: '${a.date}' },`)
    .join('\n');

  const output = `// This file is auto-generated by scripts/generate-mdx-index.js
// Do not edit manually - your changes will be overwritten!
// To add a new article, create a .mdx file in /content/writing/ and run: npm run generate:mdx

// Sorted article list (newest first) - extracted from MDX frontmatter
export const articleList: { id: string; title: string; date: string }[] = [
${articleListStr}
];
`;

  fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
  console.log(`✅ Generated ${OUTPUT_FILE}`);
  console.log(`📦 Exported ${files.length} article(s) to index.ts`);
}

try {
  generateIndexFile();
} catch (error) {
  console.error('❌ Error generating MDX index:', error);
  process.exit(1);
}
